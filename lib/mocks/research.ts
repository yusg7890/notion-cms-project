/** 기준일로부터 n개월 전 Date 반환 */
function monthsAgo(n: number): Date {
  const d = new Date('2026-04-23')
  d.setMonth(d.getMonth() - n)
  return d
}

/** 기준일로부터 n일 전 Date 반환 */
function daysAgo(n: number): Date {
  const d = new Date('2026-04-23')
  d.setDate(d.getDate() - n)
  return d
}

