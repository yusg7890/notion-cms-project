/** 발행일 내림차순으로 정렬된 전체 리서치 목록 반환 */
export function getMockResearches(): Research[] {
  return [...MOCK_RESEARCHES].sort(
    (a, b) => b.publishedAt.getTime() - a.publishedAt.getTime()
  )
}

/** ID로 단일 리서치 조회 */
export function getMockResearchById(id: string): Research | undefined {
  return MOCK_RESEARCHES.find((r) => r.id === id)
}

/**
 * 티커 기준 종목 히스토리 조회
 * researches는 publishedAt 오름차순 정렬 (차트 시계열 표시용)
 * 해당 티커가 없으면 undefined 반환
 */
export function getMockStockHistory(ticker: string): StockHistory | undefined {
  const researches = MOCK_RESEARCHES.filter((r) => r.ticker === ticker)
  if (researches.length === 0) return undefined

  const sorted = [...researches].sort(
    (a, b) => a.publishedAt.getTime() - b.publishedAt.getTime()
  )

  // 첫 번째 리서치의 메타 정보 기준으로 StockHistory 구성
  const first = sorted[0]
  return {
    ticker: first.ticker,
    stockName: first.stockName,
    sector: first.sector,
    currency: first.currency,
    researches: sorted,
  }
}
