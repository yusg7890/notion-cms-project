/** ticker 기준으로 StockHistory 집계 반환 */
export function getMockStockHistory(ticker: string): StockHistory | undefined {
  const researches = MOCK_RESEARCHES.filter((r) => r.ticker === ticker)
  if (researches.length === 0) return undefined

  const first = researches[0]
  const currencies = new Set(researches.map((r) => r.currency))
  // 통화 혼재 시 첫 번째 통화 기준으로 설정 (차트에서 경고 표시)
  const currency = currencies.size === 1 ? first.currency : first.currency

  return {
    ticker: first.ticker,
    stockName: first.stockName,
    sector: first.sector,
    currency,
    researches: [...researches].sort(
      (a, b) => a.publishedAt.getTime() - b.publishedAt.getTime(),
    ),
  }
}
